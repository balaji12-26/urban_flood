/* FloodSense — API client, shared state, tiny event bus, boot sequence. Loaded first. */
(function () {
  const FS = window.FS = window.FS || {};

  // ───────── state ─────────
  FS.state = {
    data: null,            // last GET /api/zones payload
    zonesById: {},
    selectedZone: null,
    scenario: { rainfall_multiplier: 1.0, drainage_blockage: 0.0, water_level_rise_cm: 0 },
    scope: 'zone',         // 'zone' | 'all'
    sensorMode: 'live',    // 'live' | 'frozen'
    live: true,            // allow Open-Meteo network fetch
    weatherMode: 'live',   // 'live' | 'sample' (labelled sample storm for demos)
    showWaterLevel: true,
    usingMock: false,
  };

  // ───────── event bus ─────────
  const handlers = {};
  FS.bus = {
    on(evt, fn) { (handlers[evt] = handlers[evt] || []).push(fn); },
    emit(evt, payload) { (handlers[evt] || []).forEach(fn => { try { fn(payload); } catch (e) { console.error(evt, e); } }); },
  };

  // ───────── helpers ─────────
  FS.LEVEL_COLORS = { LOW: '#2ecc8f', MODERATE: '#f2c94c', HIGH: '#ff8c42', CRITICAL: '#ff4d6d' };
  FS.FACTOR_LABELS = {
    rainfall: 'Current rainfall', forecast: 'Forecast 6h rainfall', water_level: 'Water level',
    drainage: 'Drainage deficit', terrain: 'Terrain risk', history: 'Flood history',
  };
  FS.levelColor = lvl => FS.LEVEL_COLORS[lvl] || '#4f8cff';
  FS.badge = label => `<span class="badge badge-${String(label).toLowerCase()}">${label}</span>`;
  FS.fmt1 = n => (n == null || isNaN(n)) ? '—' : Number(n).toFixed(1);
  FS.esc = s => String(s == null ? '' : s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  FS.timeAgo = ts => { if (!ts) return '—'; const s = Math.max(0, Math.round(Date.now() / 1000 - ts)); return s < 60 ? `${s}s ago` : s < 3600 ? `${Math.round(s / 60)}m ago` : `${Math.round(s / 3600)}h ago`; };

  // ───────── API ─────────
  async function getJSON(url, opts) {
    const r = await fetch(url, Object.assign({ headers: { 'Accept': 'application/json' } }, opts || {}));
    if (!r.ok) {
      let detail = '';
      try { detail = (await r.json()).error || ''; } catch (_) { /* ignore */ }
      throw new Error(`${r.status} ${url} ${detail}`.trim());
    }
    return r.json();
  }
  const q = obj => Object.entries(obj).filter(([, v]) => v !== undefined && v !== null && v !== '')
    .map(([k, v]) => `${encodeURIComponent(k)}=${encodeURIComponent(v)}`).join('&');

  FS.api = {
    async getZones() {
      const s = FS.state;
      const url = `/api/zones?${q({ live: s.live ? 1 : 0, sensor_mode: s.sensorMode, weather: s.weatherMode })}`;
      try {
        const d = await getJSON(url);
        s.usingMock = false;
        return d;
      } catch (e) {
        // Fallback for parallel frontend dev: identical schema, generated by the real engine.
        const m = await getJSON('/mock/mock.json').catch(() => getJSON('../mock/mock.json'));
        s.usingMock = true;
        m._mock_error = e.message;
        return m;
      }
    },
    getGeoJSON: () => getJSON('/api/geojson').catch(() => null),
    postScenario(body) {
      const s = FS.state;
      return getJSON('/api/scenario', {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(Object.assign({ live: s.live, sensor_mode: s.sensorMode, weather: s.weatherMode }, body)),
      });
    },
    getForecastCurve(zone, scenario) {
      return getJSON(`/api/forecast-curve?${q(Object.assign({ zone, live: FS.state.live ? 1 : 0, weather: FS.state.weatherMode }, scenario || {}))}`);
    },
    getValidation(kind, params) { return getJSON(`/api/validation/${kind}?${q(Object.assign({ live: FS.state.live ? 1 : 0, weather: FS.state.weatherMode }, params || {}))}`); },
    getMethods: () => getJSON('/api/methods'),
  };

  // ───────── status UI ─────────
  function renderStatus(d) {
    const w = d.weather || {};
    const pw = document.getElementById('pill-weather');
    const stale = !!w.stale;
    pw.className = 'pill ' + (stale ? 'pill-stale' : 'pill-live');
    const src = w.source === 'open-meteo' ? 'Open-Meteo LIVE'
      : w.source === 'cache' ? 'Open-Meteo (cached)'
      : w.source === 'stale-cache' ? 'Open-Meteo STALE cache'
      : w.source === 'sample-storm' ? 'SAMPLE storm (not live)'
      : 'OFFLINE fallback';
    pw.textContent = `Rain ${FS.fmt1(w.precip_1h_mm)} mm/h · ${src}`;
    pw.title = `source=${w.source} age=${w.age_seconds ?? '—'}s ${w.error ? '· ' + w.error : ''}`;
    document.getElementById('pill-updated').textContent = `updated ${FS.timeAgo(d.generated_at)}`;

    const b = document.getElementById('banner-stale');
    const msgs = [];
    if (FS.state.usingMock) msgs.push(`Backend unreachable (${FS.esc(d._mock_error || '')}). Showing mock.json generated by the engine — values are not live.`);
    if (w.source === 'sample-storm') msgs.push(`Weather is a <strong>SAMPLE storm</strong> (${FS.fmt1(w.precip_1h_mm)} mm/h now, ${FS.fmt1((w.forecast_6h_mm || []).reduce((a, b) => a + b, 0))} mm next 6h) chosen for demonstration. It is not live. Switch off "Sample storm" to return to Open-Meteo.`);
    else if (stale && !FS.state.usingMock) msgs.push(`Weather data is <strong>${w.source === 'offline-fallback' ? 'an offline fallback sample' : 'stale'}</strong> (${w.error ? FS.esc(w.error) : 'cache older than 10 min or live fetch disabled'}). Rainfall factors are illustrative until a live fetch succeeds.`);
    msgs.push(`Water level is <strong>SIMULATED</strong> for every zone (synthetic sensor, ${FS.esc((d.sensor || {}).mode || 'live')} mode). No real device exists.`);
    b.innerHTML = msgs.join('<br>');
    b.classList.remove('hidden');
  }

  // ───────── load + boot ─────────
  FS.load = async function () {
    const err = document.getElementById('banner-error');
    try {
      const d = await FS.api.getZones();
      FS.state.data = d;
      FS.state.zonesById = {};
      d.zones.forEach(z => { FS.state.zonesById[z.id] = z; });
      if (!FS.state.selectedZone || !FS.state.zonesById[FS.state.selectedZone]) FS.state.selectedZone = d.zones[0].id;
      renderStatus(d);
      err.classList.add('hidden');
      FS.bus.emit('data', d);
      FS.bus.emit('zone:select', FS.state.selectedZone);
    } catch (e) {
      err.textContent = `Could not load zones: ${e.message}. Start the backend with "python run.py".`;
      err.classList.remove('hidden');
    }
  };

  FS.boot = function () {
    // tabs
    document.querySelectorAll('.tab').forEach(btn => btn.addEventListener('click', () => {
      document.querySelectorAll('.tab').forEach(b => b.classList.toggle('active', b === btn));
      document.querySelectorAll('.panel').forEach(p => p.classList.toggle('active', p.id === `panel-${btn.dataset.tab}`));
      FS.bus.emit('tab', btn.dataset.tab);
    }));
    document.getElementById('btn-refresh').addEventListener('click', () => FS.load());
    document.getElementById('toggle-frozen').addEventListener('change', e => { FS.state.sensorMode = e.target.checked ? 'frozen' : 'live'; FS.load(); });
    document.getElementById('toggle-live').addEventListener('change', e => { FS.state.live = e.target.checked; FS.load(); });
    document.getElementById('toggle-sample').addEventListener('change', e => { FS.state.weatherMode = e.target.checked ? 'sample' : 'live'; FS.load(); });

    FS.bus.emit('boot');
    FS.load();
    setInterval(() => { if (FS.state.sensorMode === 'live' && !FS.state.usingMock) FS.load(); }, 30000);
  };
})();
